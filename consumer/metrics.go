package main

import (
    "github.com/prometheus/client_golang/prometheus"
    "github.com/prometheus/client_golang/prometheus/promauto"
)

// Count weather forecasts evaluated by the Kafka consumer.
var forecastsEvaluated = promauto.NewCounter(
    prometheus.CounterOpts{
        Name: "weather_forecasts_evaluated_total",
        Help: "Total number of weather forecasts evaluated by the Kafka consumer.",
    },
)

// Count weather alerts by type.
var weatherAlerts = promauto.NewCounterVec(
    prometheus.CounterOpts{
        Name: "weather_alerts_total",
        Help: "Total number of weather alerts generated by type.",
    },
    []string{"type"},
)
